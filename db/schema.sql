-- ---------- account ----------
 
-- Login accounts for students and employers
CREATE TABLE users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY,
    email         VARCHAR(254) NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    role          VARCHAR(20)  NOT NULL,
    name          VARCHAR(100) NOT NULL,
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT pk_users PRIMARY KEY (id)
);
 
CREATE UNIQUE INDEX uk_users_email ON users (lower(email));
 
 
-- ---------- profile ----------
 
-- Student profile, 1:1 with users (user_id = users.id)
CREATE TABLE student_profiles (
    user_id              BIGINT       NOT NULL,
    phone                VARCHAR(30),
    major                VARCHAR(100),
    year_of_study        VARCHAR(30),
    expected_hourly_rate NUMERIC(8,2),
    match_alerts_enabled BOOLEAN      NOT NULL DEFAULT true,
    updated_at           TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT pk_student_profiles PRIMARY KEY (user_id)
);
 
-- Employer profile, 1:1 with users (user_id = users.id)
CREATE TABLE employer_profiles (
    user_id       BIGINT        NOT NULL,
    display_name  VARCHAR(100)  NOT NULL,
    bio           VARCHAR(1000),
    contact_email VARCHAR(254)  NOT NULL,
    phone         VARCHAR(30),
    updated_at    TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT pk_employer_profiles PRIMARY KEY (user_id)
);
 
-- Shared skill / language tags
CREATE TABLE tags (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY,
    name       VARCHAR(50)  NOT NULL,
    created_at TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT pk_tags PRIMARY KEY (id),
    CONSTRAINT uk_tags_name UNIQUE (name)
);
 
-- Student <-> tag (many-to-many)
CREATE TABLE student_tags (
    student_id BIGINT NOT NULL,
    tag_id     BIGINT NOT NULL,
    CONSTRAINT pk_student_tags PRIMARY KEY (student_id, tag_id)
);
 
-- Student weekly free time slots
CREATE TABLE student_time_slots (
    student_id   BIGINT  NOT NULL,
    day_of_week  INTEGER NOT NULL,
    start_minute INTEGER NOT NULL,
    end_minute   INTEGER NOT NULL,
    CONSTRAINT pk_student_time_slots PRIMARY KEY (student_id, day_of_week, start_minute)
);
 
 
-- ---------- posting ----------
 
-- Job postings created by employers
CREATE TABLE postings (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY,
    employer_id  BIGINT        NOT NULL,
    title        VARCHAR(100)  NOT NULL,
    job_type     VARCHAR(20)   NOT NULL,
    hourly_rate  NUMERIC(8,2)  NOT NULL,
    weekly_hours NUMERIC(4,1)  NOT NULL,
    area         VARCHAR(20)   NOT NULL,
    address      VARCHAR(200)  NOT NULL,
    description  VARCHAR(2000),
    headcount    INTEGER       NOT NULL,
    status       VARCHAR(10)   NOT NULL DEFAULT 'OPEN',
    close_reason VARCHAR(10),
    closed_at    TIMESTAMPTZ,
    created_at   TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at   TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT pk_postings PRIMARY KEY (id)
);
 
CREATE INDEX idx_postings_employer_status_created ON postings (employer_id, status, created_at DESC);
CREATE INDEX idx_postings_status_created ON postings (status, created_at DESC);
 
-- Posting <-> tag (many-to-many)
CREATE TABLE posting_tags (
    posting_id BIGINT NOT NULL,
    tag_id     BIGINT NOT NULL,
    CONSTRAINT pk_posting_tags PRIMARY KEY (posting_id, tag_id)
);
 
-- Posting weekly work time slots
CREATE TABLE posting_time_slots (
    posting_id   BIGINT  NOT NULL,
    day_of_week  INTEGER NOT NULL,
    start_minute INTEGER NOT NULL,
    end_minute   INTEGER NOT NULL,
    CONSTRAINT pk_posting_time_slots PRIMARY KEY (posting_id, day_of_week, start_minute)
);
 
 
-- ---------- application ----------
 
-- Student applications to postings
CREATE TABLE applications (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY,
    posting_id    BIGINT       NOT NULL,
    student_id    BIGINT       NOT NULL,
    status        VARCHAR(20)  NOT NULL,
    status_reason VARCHAR(30),
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT pk_applications PRIMARY KEY (id),
    CONSTRAINT uk_applications_posting_student UNIQUE (posting_id, student_id)
);
 
CREATE INDEX idx_applications_student_updated ON applications (student_id, updated_at DESC);
 
-- Status history of each application, written only by ApplicationStateMachine
CREATE TABLE application_status_history (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY,
    application_id BIGINT       NOT NULL,
    from_status    VARCHAR(20),
    to_status      VARCHAR(20)  NOT NULL,
    actor_type     VARCHAR(10)  NOT NULL,
    actor_user_id  BIGINT,
    reason         VARCHAR(30),
    created_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT pk_application_status_history PRIMARY KEY (id)
);
 
CREATE INDEX idx_application_status_history_application_created ON application_status_history (application_id, created_at);
 
 
-- ---------- notification ----------
 
-- In-app notifications
CREATE TABLE notifications (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY,
    recipient_id BIGINT       NOT NULL,
    type         VARCHAR(30)  NOT NULL,
    message      VARCHAR(300) NOT NULL,
    target_type  VARCHAR(20)  NOT NULL,
    target_id    BIGINT       NOT NULL,
    read_at      TIMESTAMPTZ,
    created_at   TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT pk_notifications PRIMARY KEY (id)
);
 
CREATE INDEX idx_notifications_recipient_created ON notifications (recipient_id, created_at DESC);
CREATE INDEX idx_notifications_recipient_unread ON notifications (recipient_id) WHERE read_at IS NULL;
CREATE UNIQUE INDEX uk_notifications_match_alert ON notifications (recipient_id, target_id) WHERE type = 'NEW_MATCHING_JOB';
 
 
-- ---------- review (P1) ----------
 
-- Two-way reviews on completed applications
CREATE TABLE reviews (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY,
    application_id  BIGINT       NOT NULL,
    reviewer_role   VARCHAR(20)  NOT NULL,
    reviewer_id     BIGINT       NOT NULL,
    reviewee_id     BIGINT       NOT NULL,
    paid_on_time    BOOLEAN,
    shift_stability INTEGER,
    overall_rating  INTEGER,
    attendance      INTEGER,
    attitude        INTEGER,
    comment         VARCHAR(500),
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT pk_reviews PRIMARY KEY (id),
    CONSTRAINT uk_reviews_application_role UNIQUE (application_id, reviewer_role)
);
 
CREATE INDEX idx_reviews_reviewee_created ON reviews (reviewee_id, created_at DESC);
 